import assert from 'node:assert/strict';
import { correctReviewedAnswer, updateCorrectedAttempt } from '../src/utils/manualAnswerCorrection.js';
import { calculateReadingBand, calculateListeningBand } from '../src/utils/bandCalculator.js';
import { recordAttempt, getAttemptById, getPerformanceStore } from '../src/utils/performanceStore.js';
import { serializeAttempt, mergeAttemptData } from '../src/utils/attemptPayload.js';
const storage = new Map();
globalThis.localStorage = { getItem:k=>storage.get(k)||null, setItem:(k,v)=>storage.set(k,v) };
const items = Object.fromEntries(Array.from({length:40},(_,i)=>[`q${i+1}`,{candidateAnswer:i===39?'':'compass needle',officialAnswer:'compass',finalResult:i<29?'CORRECT':i===29?'UNCERTAIN':'INCORRECT',unresolved:i===29}]));
const base = {status:'completed',raw:29,total:40,band:6,percentage:73,unresolvedCount:1,itemResults:items};
const frozen = JSON.stringify(base);
for(const [skill,toBand] of [['reading',calculateReadingBand],['listening',calculateListeningBand]]) {
 let next=correctReviewedAnswer(base,skill,'q30');
 assert.equal(next.raw,30);assert.equal(next.band,toBand(30));assert.equal(next.percentage,75);
 assert.equal(next.unresolvedCount,0);assert.equal(next.isProvisional,false);assert.equal(next.scoreRange,null);
 assert.equal(next.itemResults.q30.evaluationMethod,'MANUAL');
 assert.equal(next.itemResults.q30.officialAnswer,'compass');assert.equal(next.itemResults.q30.candidateAnswer,'compass needle');
 assert.equal(correctReviewedAnswer(next,skill,'q30'),next,'double click cannot add another mark');
 assert.equal(correctReviewedAnswer(base,skill,'q1'),base,'already correct cannot be credited twice');
 assert.equal(correctReviewedAnswer(base,skill,'q40'),base,'blank answers cannot gain credit');
 const undone=correctReviewedAnswer(next,skill,'q30',next.itemResults,true);
 assert.equal(undone.raw,29);assert.equal(undone.unresolvedCount,1);assert.equal(undone.itemResults.q30.finalResult,'UNCERTAIN');
 assert.equal(undone.itemResults.q30.manualCorrection,null);
 const remote=mergeAttemptData(next,undone);
 assert.equal(remote.itemResults.q30.manualCorrection,null,'Undo clears the persisted override through recursive cloud merge');
 assert.equal(remote.raw,29);
 const second=correctReviewedAnswer(next,skill,'q31');assert.equal(second.raw,31);
 const oneUndo=correctReviewedAnswer(second,skill,'q30',second.itemResults,true);assert.equal(oneUndo.raw,30);assert(oneUndo.itemResults.q31.manualCorrection);
 const attempt={id:'saved-'+skill,type:skill,completedAt:'2026-01-01',overallBand:6,[skill]:base};
 recordAttempt(attempt);recordAttempt(updateCorrectedAttempt(attempt,skill,next));
 const restored=getAttemptById(attempt.id);assert.equal(restored[skill].raw,30);assert.equal(restored.completedAt,'2026-01-01');
 assert.equal(getPerformanceStore().attempts.filter(a=>a.id===attempt.id).length,1);
 const mock={id:'mock',type:'full_mock',completedAt:'2026-01-01',band:6,skills:{reading:base,listening:{status:'completed',band:6},writing:{status:'completed',band:6},speaking:{status:'completed',band:6}}};
 const updated=updateCorrectedAttempt(mock,'reading',{...next,band:8});assert.equal(updated.overallBand,6.5);assert.equal(updated.band,6.5);
 assert.equal(updated.skills.writing,mock.skills.writing);assert.equal(serializeAttempt(updated).band,6.5);
 const partial=updateCorrectedAttempt({...mock,skills:{...mock.skills,writing:{status:'failed',band:null}}},'reading',next);assert.equal(partial.overallBand,null);
 let drill={correct:0,total:1,accuracy:0,itemResults:{q30:items.q30}};
 drill=correctReviewedAnswer(drill,skill,'q30');assert.equal(drill.correct,1);assert.equal(drill.accuracy,100);assert.equal(drill.band,null);
 drill=correctReviewedAnswer(drill,skill,'q30',drill.itemResults,true);assert.equal(drill.correct,0);assert.equal(drill.band,null);
}
assert.equal(JSON.stringify(base),frozen,'manual correction never mutates the original result or key');
console.log('Manual corrections: Reading/Listening marks, bands, pending ranges, drills, Undo, history, mock overall and cloud merge passed.');
