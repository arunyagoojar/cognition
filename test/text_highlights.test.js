import assert from 'node:assert/strict';
import { addTextHighlights, changeTextHighlights, highlightAnchors, removeTextHighlight, resolveTextHighlights, undoTextHighlights } from '../src/utils/textHighlights.js';

const text = '0 of 2 selected. Alpha passage phrase. Question wording. Beta passage phrase.';
const first = text.indexOf('Alpha'), second = text.indexOf('Beta');
const legacy = { text, ranges: [[first, first + 20], [second, second + 19]] };
const changed = text.replace('0 of 2 selected.', '1 of 2 selected, answer recorded.');
assert.equal(resolveTextHighlights(legacy, changed).ranges.length, 2, 'unrelated dynamic text must not hide all marks');
const migrated = addTextHighlights(legacy, changed, []);
assert.equal(migrated.version, 3);
assert(!('text' in migrated), 'new drafts do not repeat the entire source text');
assert.equal(resolveTextHighlights(migrated, changed).ranges.length, 2);
const removed = changed.replace('Alpha passage phrase', 'temporarily hidden');
assert.equal(resolveTextHighlights(migrated, removed).ranges.length, 1, 'one missing quote does not erase other marks');
const retained = addTextHighlights(migrated, removed, []);
assert.equal(resolveTextHighlights(retained, changed).ranges.length, 2, 'temporarily unavailable anchors remain recoverable');
assert.deepEqual(resolveTextHighlights({ text, ranges: [null, [-1, 20], [5, 2], ['1', '3']] }, text).ranges, []);
const repeated = 'first region: repeated word. second region: repeated word. third region.';
const start = repeated.lastIndexOf('repeated');
const duplicate = addTextHighlights(null, repeated, [[start, start + 8]]);
const moved = 'prefixed content. ' + repeated;
assert.deepEqual(resolveTextHighlights(duplicate, moved).ranges, [[moved.lastIndexOf('repeated'), moved.lastIndexOf('repeated') + 8]], 'context disambiguates duplicate words');
const manyText = Array.from({ length: 1500 }, (_, i) => `Paragraph ${i} has a distinct highlighted phrase ${i}. `).join('');
const ranges = [...manyText.matchAll(/distinct highlighted phrase \d+/g)].map(m => [m.index, m.index + m[0].length]);
const many = addTextHighlights(null, manyText, ranges);
assert.equal(resolveTextHighlights(many, manyText).ranges.length, 1500);
assert.equal(resolveTextHighlights(many, 'changed counter. ' + manyText).ranges.length, 1500);
console.log('Highlight anchors: legacy recovery, dynamic text, duplicate quotes, missing content, and 1,500 marks passed.');
let history = changeTextHighlights(null, migrated);
const originalCount = highlightAnchors(history).length;
history = changeTextHighlights(history, removeTextHighlight(history, 0));
assert.equal(highlightAnchors(history).length, originalCount - 1);
history = undoTextHighlights(JSON.parse(JSON.stringify(history)));
assert.equal(highlightAnchors(history).length, originalCount);
history = changeTextHighlights(history, null);
assert.equal(highlightAnchors(history).length, 0);
history = undoTextHighlights(history);
assert.equal(highlightAnchors(history).length, originalCount);
assert.equal(changeTextHighlights(history, { anchors: highlightAnchors(history) }), history, 'no-op selections do not consume Undo history');
console.log('Individual removal, Undo, clear recovery, persisted history and no-op changes passed.');
